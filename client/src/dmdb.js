const dmdbImages = import.meta.glob("./Image/LeSeMeDa/*", { eager: true, query: "?url", import: "default" });

function normalizeForMatch(value) {
    if (!value) return "";
    return value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");
}

const imageNameAliases = {
    "cicer-arietinum": "cicer-arientinum",
};

function getImageUrl(scientificName) {
    const normalizedName = normalizeForMatch(scientificName);
    const namesToMatch = [normalizedName, imageNameAliases[normalizedName]].filter(Boolean);

    for (const [path, url] of Object.entries(dmdbImages)) {
        const fileName = path.split("/").pop();
        const filename = fileName.slice(0, fileName.lastIndexOf("."));
        const normalizedFilename = normalizeForMatch(filename);
        if (namesToMatch.some((name) =>
            normalizedFilename === name || normalizedFilename.startsWith(`${name}-`)
        )) {
            return url;
        }
    }
    return "";
}

