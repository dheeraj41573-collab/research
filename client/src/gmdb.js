const gmdbImages = import.meta.glob("./Image/gmdb/*", { eager: true, query: "?url", import: "default" });

function normalizeForMatch(value) {
    if (!value) return "";
    return value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "");
}

function getImageUrl(scientificName) {
    const normalizedName = normalizeForMatch(scientificName);
    for (const [path, url] of Object.entries(gmdbImages)) {
        const filename = path.split("/").pop().split(".").shift();
        if (normalizeForMatch(filename) === normalizedName) {
            return url;
        }
    }
    return "/Image/gmdb/sergei.jpg";
}

